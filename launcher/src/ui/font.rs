pub fn glyph(c: char) -> [u8; 7] {
    let c = c.to_ascii_uppercase();
    GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, r)| *r).unwrap_or([0; 7])
}

pub fn width(s: &str, scale: i32) -> i32 {
    let n = s.chars().count() as i32;
    if n == 0 { 0 } else { (n * ADVANCE - 1) * scale }
}

/// Greedy word wrap by character count.
pub fn wrap(s: &str, max_chars: usize) -> Vec<String> {
    let mut lines = Vec::new();
    let mut cur = String::new();
    // Words longer than a line get split so nothing runs off a panel.
    let words: Vec<String> = s
        .split_whitespace()
        .flat_map(|w| {
            let chars: Vec<char> = w.chars().collect();
            chars.chunks(max_chars.max(1)).map(|c| c.iter().collect::<String>()).collect::<Vec<_>>()
        })
        .collect();
    for word in words.iter().map(String::as_str) {
        if !cur.is_empty() && cur.len() + 1 + word.len() > max_chars {
            lines.push(std::mem::take(&mut cur));
        }
        if !cur.is_empty() {
            cur.push(' ');
        }
        cur.push_str(word);
    }
    if !cur.is_empty() {
        lines.push(cur);
    }
    lines
}

#[cfg(test)]
mod tests {
    #[test]
    fn wraps_and_splits_long_words() {
        let l = super::wrap("one two three", 7);
        assert_eq!(l, vec!["one two", "three"]);
        let l = super::wrap("abcdefghijkl", 5);
        assert_eq!(l, vec!["abcde", "fghij", "kl"]);
        assert!(super::wrap("", 5).is_empty());
    }
}
